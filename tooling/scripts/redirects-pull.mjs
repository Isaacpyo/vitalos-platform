// Pulls published `redirect` documents from Sanity into the version-controlled redirect map
// (apps/web/src/features/redirects/generated.ts) so redirects are reviewed in a pull request
// like any other change (ADR-018). The seed rules live in redirect-map.ts and are never touched.
//
// Usage:
//   node tooling/scripts/redirects-pull.mjs            # fetch, validate, write generated.ts
//   node tooling/scripts/redirects-pull.mjs --check    # fetch and fail if generated.ts differs
//
// Environment (read-only; nothing is written to Sanity):
//   NEXT_PUBLIC_SANITY_PROJECT_ID   required
//   NEXT_PUBLIC_SANITY_DATASET      default "development"
//   NEXT_PUBLIC_SANITY_API_VERSION  default "2025-02-19"
//   SANITY_API_READ_TOKEN           optional for a public dataset
//
// The Sanity `redirect` document (workstream C1) has the fields `source`, `destination` and
// `status` (301 | 308 | 410). This is an owner-run tool: it is not part of CI and was written
// without access to a Sanity project. Redirects reach the site through this pull, a reviewed
// commit and a redeploy; publishing a redirect in the Studio does not change the live site.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(fileURLToPath(new URL("../..", import.meta.url)));
const redirectsDir = join(root, "apps/web/src/features/redirects");
const generatedFile = join(redirectsDir, "generated.ts");

export const QUERY = `*[_type == "redirect" && !(_id in path("drafts.**"))] | order(source asc) {
  source, destination, status
}`;

/** @param {unknown} value */
const asStatus = (value) => (typeof value === "string" ? Number(value) : value);

/**
 * Normalises raw Sanity rows into redirect rules: trims, drops unknown fields and keeps `status`
 * to 301, 308 or 410. Throws on rows that cannot be a rule; semantic checks (chains, loops,
 * blanket redirects, live routes) are done by `validateRedirects` afterwards.
 *
 * @param {unknown} rows
 * @returns {{ source: string; destination?: string; status: 301 | 308 | 410 }[]}
 */
export function normaliseRows(rows) {
  if (!Array.isArray(rows)) throw new Error("Sanity returned no redirect list.");
  const rules = rows.map((row, index) => {
    const source = typeof row?.source === "string" ? row.source.trim() : "";
    const status = asStatus(row?.status);
    if (!source) throw new Error(`Redirect row ${index + 1} has no source.`);
    if (status !== 301 && status !== 308 && status !== 410) {
      throw new Error(`Redirect ${source} has an unsupported status (use 301, 308 or 410).`);
    }
    if (status === 410) return { source, status };
    const destination = typeof row?.destination === "string" ? row.destination.trim() : "";
    if (!destination) throw new Error(`Redirect ${source} has no destination.`);
    return { source, destination, status };
  });
  return rules.sort((a, b) => a.source.localeCompare(b.source));
}

/** @param {ReturnType<typeof normaliseRows>} rules */
export function renderGeneratedModule(rules) {
  const body = rules
    .map((rule) =>
      rule.status === 410
        ? `  { source: ${JSON.stringify(rule.source)}, status: 410 },`
        : `  { source: ${JSON.stringify(rule.source)}, destination: ${JSON.stringify(rule.destination)}, status: ${rule.status} },`,
    )
    .join("\n");
  const list = rules.length === 0 ? "[]" : `[\n${body}\n]`;
  return `import type { RedirectRule } from "./types";

/**
 * GENERATED by \`node tooling/scripts/redirects-pull.mjs\` from the published Sanity \`redirect\`
 * documents. Do not edit by hand. Empty until the owner has approved redirects in the Studio.
 * The unit tests in \`redirects.test.ts\` validate this list together with the seed.
 */
export const generatedRedirects: readonly RedirectRule[] = ${list};
`;
}

/**
 * @param {Record<string, string | undefined>} env
 * @param {typeof fetch} fetchImpl
 */
export async function pullRedirects(env, fetchImpl = fetch) {
  const projectId = env.NEXT_PUBLIC_SANITY_PROJECT_ID;
  if (!projectId) throw new Error("NEXT_PUBLIC_SANITY_PROJECT_ID is not set.");
  const dataset = env.NEXT_PUBLIC_SANITY_DATASET || "development";
  const version = env.NEXT_PUBLIC_SANITY_API_VERSION || "2025-02-19";
  const url = new URL(`https://${projectId}.api.sanity.io/v${version}/data/query/${dataset}`);
  url.searchParams.set("query", QUERY);
  url.searchParams.set("perspective", "published");
  const headers = env.SANITY_API_READ_TOKEN
    ? { authorization: `Bearer ${env.SANITY_API_READ_TOKEN}` }
    : {};
  const response = await fetchImpl(url, { headers });
  if (!response.ok) throw new Error(`Sanity query failed with HTTP ${response.status}.`);
  const payload = await response.json();
  return normaliseRows(payload.result);
}

async function validate(rules) {
  const { validateRedirects } = await import(pathToFileURL(join(redirectsDir, "validate.ts")).href);
  const issues = validateRedirects(rules);
  if (issues.length > 0) {
    throw new Error(
      `Pulled redirects are invalid:\n${issues.map((i) => `- ${i.source}: ${i.message}`).join("\n")}`,
    );
  }
}

async function main() {
  const check = process.argv.includes("--check");
  const rules = await pullRedirects(process.env);
  await validate(rules);

  const next = renderGeneratedModule(rules);
  if (check) {
    const current = readFileSync(generatedFile, "utf8");
    const normalise = (text) =>
      text
        .replace(/\s+/g, " ")
        .replace(/,\s*\]/g, "]")
        .trim();
    if (normalise(current) !== normalise(next)) {
      console.error("generated.ts is out of date. Run: node tooling/scripts/redirects-pull.mjs");
      process.exit(1);
    }
    console.log(`Redirects up to date (${rules.length} from Sanity).`);
    return;
  }

  writeFileSync(generatedFile, next);
  const prettier = join(
    dirname(fileURLToPath(import.meta.url)),
    "../../node_modules/prettier/bin/prettier.cjs",
  );
  execFileSync(process.execPath, [prettier, "--write", generatedFile], { stdio: "inherit" });
  console.log(
    `Wrote ${rules.length} redirect(s) to ${generatedFile}. Review the diff before committing.`,
  );
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
  });
}
