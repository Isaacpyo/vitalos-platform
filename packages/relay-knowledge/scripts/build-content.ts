/**
 * Compiles content/*.md into src/generated/repo-content.ts so the website can import the seed
 * knowledge without reading files at run time (serverless file tracing). The generated module is
 * committed; `repo.test.ts` fails when it is out of date. Run after editing content:
 *
 *   pnpm --filter @vitalos/relay-knowledge build-content
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

export function renderGenerated(): string {
  const dir = join(root, "content");
  const files = readdirSync(dir)
    .filter((f) => f.endsWith(".md"))
    .sort();
  const items = files.map((file) => {
    const text = readFileSync(join(dir, file), "utf8").replace(/\r\n?/g, "\n");
    return `  { file: ${JSON.stringify(file)}, text: ${JSON.stringify(text)} },`;
  });
  return [
    "// Generated by scripts/build-content.ts from content/*.md. Do not edit by hand.",
    "export const repoContentFiles: readonly { file: string; text: string }[] = [",
    ...items,
    "];",
    "",
  ].join("\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(join(root, "src/generated/repo-content.ts"), renderGenerated(), "utf8");
  console.log("wrote src/generated/repo-content.ts");
}
